import streamlit as st

# แสดงชื่อแอปพลิเคชัน
st.title("🛒 แอปพลิเคชั่นคำนวณราคาสินค้ารวม VAT 7%")

# สร้างช่องรับข้อมูลตัวเลขราคา (ตั้งค่าเริ่มต้นเป็น 500.00)
price = st.number_input("กรอกราคาสินค้า (บาท):", value=500.0)

# คำนวณภาษี VAT 7% และราคาสุทธิก่อนภาษี
vat = price * 0.07
net_price = price - vat

# แสดงผลการคำนวณ
st.header(f"• ภาษีมูลค่าเพิ่ม (VAT 7%): {vat:.2f} บาท")
st.header(f"• ราคาสุทธิ: {net_price:.2f} บาท")

# สร้างเส้นกั้น
st.divider()

# แสดงข้อมูลนักเรียน/ผู้จัดทำ
st.write("นายภควัตร สุขศรี เลขที่ 33 ม.4/11")
